INTERPOLATION = re.compile(r"\$\{([A-Za-z_][A-Za-z0-9_]*)(?::?-([^}]*))?\}")
HEALTH_URL = re.compile(r"https?://(?:localhost|127\.0\.0\.1):(\d+)(/[^\s'\"|]*)")


def fail(msg):
    sys.exit(f"generate.py: {msg}")


def resolve(value):
    """Giá trị compose → chuỗi: ${VAR:-default} lấy default (không đọc env của máy chạy script,
    để secret trên máy không lọt vào file sinh), $$ → $."""
    if isinstance(value, bool):
        return "true" if value else "false"
    text = "" if value is None else str(value)
    text = text.replace("$$", "\0")
    text = INTERPOLATION.sub(lambda m: m.group(2) or "", text)
    return text.replace("\0", "$")


def as_map(items):
    """environment/labels của compose: dict hoặc list "KEY=value"."""
    if isinstance(items, dict):
        return {k: resolve(v) for k, v in items.items()}
    result = {}
    for item in items or []:
        key, _, value = item.partition("=")
        result[key] = resolve(value)
    return result


def as_args(value):
    if value is None:
        return None
    if isinstance(value, str):
        return shlex.split(resolve(value))
    return [resolve(v) for v in value]


def namespace_of(service):
    if service in WORKLOADS:
        return WORKLOADS[service]["ns"]
    if service in JOBS:
        return JOBS[service]["ns"]
    if service in INFRA:
        return "data"
    return None


def workload_name(service):
    return WORKLOADS.get(service, {}).get("name", service)


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def rel(path):
    return pathlib.Path(os.path.relpath(path, OUT)).as_posix()


class Build:
    def __init__(self, compose, topology):
        self.compose = compose
        self.services = compose["services"]
        self.topology = topology
        self.configmaps = []  # mục configMapGenerator

    # ── cổng, probe, mount ────────────────────────────────────────────────

    def ports(self, service):
        spec = WORKLOADS.get(service, {})
        if "ports" in spec:
            return spec["ports"]
        if service in self.topology["services"]:
            return self.topology["services"][service]["ports"]
        if service in self.topology["edge_workloads"]:
            return self.topology["edge_workloads"][service]["ports"]
        fail(f"{service}: không có cổng trong topology.yaml lẫn WORKLOADS")

    def probe(self, service, ports):
        check = self.services[service].get("healthcheck")
        fallback = WORKLOADS[service].get("probe")
        if check:
            if fallback:
                fail(f"{service}: compose đã có healthcheck, bỏ probe trong WORKLOADS")
            test = " ".join(check["test"]) if isinstance(check["test"], list) else check["test"]
            match = HEALTH_URL.search(test)
            if not match:
                fail(f"{service}: không đọc được URL healthcheck từ {test!r}")
            number, path = int(match.group(1)), match.group(2)
            names = [n for n, p in ports.items() if p == number]
            if not names:
                fail(f"{service}: healthcheck dùng cổng {number} không có trong {ports}")
            return path, names[0]
        if not fallback:
            fail(f"{service}: compose không có healthcheck, cần probe trong WORKLOADS")
        return fallback

    def mounts(self, owner, namespace, volumes):
        """Bind mount ./… của compose → ConfigMap (mỗi thư mục đích một ConfigMap). Volume có tên
        và socket bị bỏ: workload ở lớp này không giữ state."""
        groups = {}
        for volume in volumes or []:
            if not isinstance(volume, str) or not volume.startswith("./"):
                continue
            source, target = volume.split(":")[:2]
            path = ROOT / source
            if path.is_dir():
                files = sorted(f for f in path.iterdir() if f.is_file())
                groups.setdefault(target, []).extend((f.name, f) for f in files)
            elif path.is_file() or path.parent == OUT:  # file do chính script này sinh
                directory, name = target.rsplit("/", 1)
                groups.setdefault(directory, []).append((name, path))
            else:
                fail(f"{owner}: không thấy {source}")
        pod_volumes, container_mounts = [], []
        for target, files in groups.items():
            name = f"{owner}-{slug(target)}"
            self.configmaps.append(
                {"name": name, "namespace": namespace, "files": [f"{key}={rel(path)}" for key, path in files]}
            )
            pod_volumes.append({"name": slug(target)[-63:], "configMap": {"name": name, "defaultMode": 0o755}})
            container_mounts.append({"name": slug(target)[-63:], "mountPath": target, "readOnly": True})
        return pod_volumes, container_mounts

    # ── container ─────────────────────────────────────────────────────────

    def image(self, service):
        svc = self.services[service]
        if "image" in svc:
            return resolve(svc["image"]), "IfNotPresent"
        # Image build tại máy: cụm kubeadm của Docker Desktop dùng chung kho image với Docker Engine.
        return f"{COMPOSE_PROJECT}-{service}:latest", "Never"

    def container(self, service, volumes_override=None, namespace=None):
        svc = self.services[service]
        namespace = namespace or namespace_of(service)
        image, pull = self.image(service)
        container = {"name": service, "image": image, "imagePullPolicy": pull}
        if svc.get("entrypoint") is not None:
            container["command"] = as_args(svc["entrypoint"])
        if svc.get("command") is not None:
            container["args"] = as_args(svc["command"])
        env = as_map(svc.get("environment"))
        if env:
            container["env"] = [{"name": k, "value": v} for k, v in env.items()]
        volumes, mounts = self.mounts(service, namespace, volumes_override or svc.get("volumes"))
        if mounts:
            container["volumeMounts"] = mounts
        if "no-new-privileges:true" in (svc.get("security_opt") or []):
            container["securityContext"] = {"allowPrivilegeEscalation": False}
        return container, volumes, env

    def check_hosts(self, service, env):
        """Mọi tên service compose xuất hiện trong env phải phân giải được trong namespace của workload."""
        namespace = namespace_of(service)
        names = set(self.services) | {"otel-collector"}
        for key, value in env.items():
            hosts = set(re.findall(r"(?:^|//|@|,)([a-z][a-z0-9-]*):\d+", value))
            if key.endswith("_HOST") or key.endswith("_SEEDS"):
                hosts.add(value)
            for host in hosts & names:
                target = namespace_of(host) or ("observability" if host == "otel-collector" else None)
                if target != namespace and host not in ALIASES.get(namespace, {}):
                    fail(f"{service}: {key} dùng '{host}' (namespace {target}) nhưng {namespace} không có alias")

    # ── manifest ──────────────────────────────────────────────────────────

    def workload(self, service):
        spec = WORKLOADS[service]
        namespace, name = spec["ns"], workload_name(service)
        ports = self.ports(service)
        container, volumes, env = self.container(service, spec.get("volumes"))
        self.check_hosts(service, env)
        if spec.get("env"):
            extra = {**env, **spec["env"]}
            container["env"] = [{"name": k, "value": v} for k, v in extra.items()]
        container["ports"] = [{"name": n, "containerPort": p} for n, p in ports.items()]

        path, port = self.probe(service, ports)
        handler = {"tcpSocket": {"port": port}} if path == "tcp" else {"httpGet": {"path": path, "port": port}}
        # Chín JVM cùng khởi động trên một node mất hơn 5 phút (đo 2026-10-21), nên cho 10 phút.
        # Liveness chỉ kiểm cổng, để dependency hỏng (readiness đỏ) không làm pod restart vòng.
        container["startupProbe"] = {**handler, "periodSeconds": 5, "timeoutSeconds": 5, "failureThreshold": 120}
        container["readinessProbe"] = {**handler, "periodSeconds": 10, "timeoutSeconds": 5, "failureThreshold": 3}
        container["livenessProbe"] = {"tcpSocket": {"port": port}, "periodSeconds": 20, "timeoutSeconds": 5, "failureThreshold": 3}
        request, limit = spec["mem"]
        container["resources"] = {"requests": {"cpu": "50m", "memory": request}, "limits": {"memory": limit}}

        pod = {
            "serviceAccountName": name,
            "automountServiceAccountToken": False,
            # Service link tiêm <SERVICE>_PORT=tcp://… và <SERVICE>_HOST; trùng tên với cấu hình
            # REDIS_PORT, KAFKA_*, AUTH_* của service.
            "enableServiceLinks": False,
        }
        if spec.get("init"):
            init, init_volumes, _ = self.container(spec["init"], namespace=namespace)
            pod["initContainers"] = [init]
            volumes = volumes + init_volumes
        pod["containers"] = [container]
        if volumes:
            pod["volumes"] = volumes

        labels = {"app.kubernetes.io/name": name}
        docs = [
            {"apiVersion": "v1", "kind": "ServiceAccount", "metadata": {"name": name, "namespace": namespace}},
            {
                "apiVersion": "v1",
                "kind": "Service",
                "metadata": {"name": service, "namespace": namespace},
                "spec": {
                    "selector": labels,
                    "ports": [{"name": n, "port": p, "targetPort": n} for n, p in ports.items()],
                },
            },
        ]
        external = self.host_ports(service, ports)
        if external:
            docs.append({
                "apiVersion": "v1",
                "kind": "Service",
                "metadata": {"name": f"{service}-external", "namespace": namespace},
                "spec": {"type": "LoadBalancer", "selector": labels, "ports": external},
            })
        docs.append({
            "apiVersion": "apps/v1",
            "kind": "Deployment",
            "metadata": {"name": name, "namespace": namespace},
            "spec": {
                "replicas": 1,
                # Một node, RAM sát: RollingUpdate chạy pod mới cạnh pod cũ, nhân đôi JVM khi apply.
                "strategy": {"type": "Recreate"},
                "selector": {"matchLabels": labels},
                "template": {"metadata": {"labels": labels}, "spec": pod},
            },
        })
        return docs

    def host_ports(self, service, ports):
        """Cổng host mở cho mọi interface của compose → LoadBalancer (Docker Desktop mở nó trên mọi
        interface của máy). Bỏ cổng container không có listener."""
        return [
            {key: value for key, value in item.items() if key != "loopback"}
            for item in self.compose_ports(service, ports)
            if not item["loopback"]
        ]

    def compose_ports(self, service, ports):
        """`ports` của compose: "host:container" (mọi interface) hoặc "127.0.0.1:host:container"."""
        by_number = {p: n for n, p in ports.items()}
        result = []
        for entry in self.services[service].get("ports") or []:
            parts = str(entry).split(":")
            if len(parts) == 3 and parts[0] == "127.0.0.1":
                loopback, parts = True, parts[1:]
            elif len(parts) == 2:
                loopback = False
            else:
                fail(f"{service}: cổng compose chưa hỗ trợ {entry!r}")
            host, target = int(parts[0]), int(parts[1].split("/")[0])
            if target in by_number:
                result.append({"name": by_number[target], "port": host, "targetPort": target, "loopback": loopback})
        return result

    def port_forwards(self):
        """Cổng compose chỉ bind 127.0.0.1 → dòng cho deploy/k8s/port-forward-dev.sh, để công cụ local
        dùng cùng địa chỉ như compose mà cụm không mở LoadBalancer."""
        lines = []
        for service in WORKLOADS:
            for item in self.compose_ports(service, self.ports(service)):
                if item["loopback"]:
                    lines.append(f"{WORKLOADS[service]['ns']} svc/{service} {item['port']}:{item['targetPort']}")
        return lines

    def network_policies(self):
        """Default deny ingress cho ecommerce và edge, rồi mỗi workload một policy cho đúng caller của nó."""
        callers = {}
        for doc in yaml.safe_load_all(MESH_POLICIES.read_text(encoding="utf-8")):
            if not doc or doc.get("kind") != "AuthorizationPolicy":
                continue
            targets = [ref["name"] for ref in doc["spec"].get("targetRefs", []) if ref.get("kind") == "Service"]
            principals = {
                principal.split("/ns/", 1)[1].replace("/sa/", "/")
                for rule in doc["spec"].get("rules", [])
                for source in rule.get("from", [])
                for principal in source["source"].get("principals", [])
            }
            for target in targets:
                callers.setdefault(target, set()).update(principals)

        def peer(source):
            namespace, account = source.split("/")
            return {
                "namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": namespace}},
                # ServiceAccount, nhãn app.kubernetes.io/name và tên workload trùng nhau ở lớp này.
                "podSelector": {"matchLabels": {"app.kubernetes.io/name": account}},
            }

        docs = [
            {
                "apiVersion": "networking.k8s.io/v1",
                "kind": "NetworkPolicy",
                "metadata": {"name": "default-deny-ingress", "namespace": namespace},
                "spec": {"podSelector": {}, "policyTypes": ["Ingress"]},
            }
            for namespace in ("ecommerce", "edge")
        ]
        for service, spec in WORKLOADS.items():
            name = workload_name(service)
            if service in PUBLIC:
                ingress = [{}]
            else:
                if service in EXTRA_CALLERS:
                    sources = set(EXTRA_CALLERS[service])
                elif service in callers:
                    sources = callers[service] - {"ecommerce/ecommerce-waypoint"}
                else:
                    fail(f"{service}: không có caller trong {rel(MESH_POLICIES)} lẫn EXTRA_CALLERS")
                ingress = [{"from": [peer(source) for source in sorted(sources | {SCRAPER})]}]
            docs.append({
                "apiVersion": "networking.k8s.io/v1",
                "kind": "NetworkPolicy",
                "metadata": {"name": f"allow-{name}", "namespace": spec["ns"]},
                "spec": {
                    "podSelector": {"matchLabels": {"app.kubernetes.io/name": name}},
                    "policyTypes": ["Ingress"],
                    "ingress": ingress,
                },
            })
        return docs

    def job(self, service):
        spec = JOBS[service]
        container, volumes, env = self.container(service)
        self.check_hosts(service, env)
        request, limit = spec["mem"]
        container["resources"] = {"requests": {"cpu": "50m", "memory": request}, "limits": {"memory": limit}}
        pod = {"enableServiceLinks": False, "restartPolicy": "OnFailure", "containers": [container]}
        if volumes:
            pod["volumes"] = volumes
        return [{
            "apiVersion": "batch/v1",
            "kind": "Job",
            "metadata": {"name": service, "namespace": spec["ns"]},
            # Spec của Job không sửa được: deploy/k8s/apply.sh xoá Job cũ trước mỗi lần apply.
            "spec": {"backoffLimit": 3, "ttlSecondsAfterFinished": 3600, "template": {"spec": pod}},
        }]

    def aliases(self):
        docs = []
        for namespace, names in ALIASES.items():
            for name, target in names.items():
                docs.append({
                    "apiVersion": "v1",
                    "kind": "Service",
                    "metadata": {"name": name, "namespace": namespace},
                    "spec": {"type": "ExternalName", "externalName": f"{name}.{target}.svc.cluster.local"},
                })
        return docs

    def routes(self):
        """Label traefik.* của compose → cấu hình file provider. Router không ghi service dùng service
        duy nhất của container, như docker provider."""
        routers, services = {}, {}
        for service, svc in self.services.items():
            labels = as_map(svc.get("labels"))
            if labels.get("traefik.enable") != "true":
                continue
            namespace = namespace_of(service)
            if namespace is None:
                fail(f"{service}: có route Traefik nhưng không có namespace")
            own_routers, own_services = {}, {}
            for key, value in labels.items():
                match = re.fullmatch(r"traefik\.http\.(routers|services)\.([^.]+)\.(.+)", key)
                if not match:
                    if key != "traefik.enable":
                        fail(f"{service}: label chưa hỗ trợ {key}")
                    continue
                kind, name, field = match.groups()
                (own_routers if kind == "routers" else own_services).setdefault(name, {})[field] = value
            for name, fields in own_services.items():
                lb = {}
                port = fields.pop("loadbalancer.server.port")
                scheme = fields.pop("loadbalancer.server.scheme", "http")
                lb["servers"] = [{"url": f"{scheme}://{service}.{namespace}.svc.cluster.local:{port}"}]
                health = {}
                for field in list(fields):
                    if field.startswith("loadbalancer.healthcheck."):
                        health[field.rsplit(".", 1)[1]] = fields.pop(field)
                if health:
                    lb["healthCheck"] = health
                if "loadbalancer.serverstransport" in fields:
                    lb["serversTransport"] = fields.pop("loadbalancer.serverstransport")
                if fields:
                    fail(f"{service}: label service chưa hỗ trợ {sorted(fields)}")
                services[name] = {"loadBalancer": lb}
            for name, fields in own_routers.items():
                router = {"rule": fields.pop("rule")}
                if "entrypoints" in fields:
                    router["entryPoints"] = fields.pop("entrypoints").split(",")
                if "service" in fields:
                    router["service"] = fields.pop("service")
                elif len(own_services) == 1:
                    router["service"] = next(iter(own_services))
                else:
                    fail(f"{service}: router {name} không ghi service")
                if "priority" in fields:
                    router["priority"] = int(fields.pop("priority"))
                if "middlewares" in fields:
                    router["middlewares"] = fields.pop("middlewares").split(",")
                if fields:
                    fail(f"{service}: label router chưa hỗ trợ {sorted(fields)}")
                routers[name] = router
        return {"http": {"routers": dict(sorted(routers.items())), "services": dict(sorted(services.items()))}}


class Dumper(yaml.SafeDumper):
    """Không sinh anchor/alias (&id001) khi hai chỗ dùng chung một dict."""

    def ignore_aliases(self, data):
        return True


def dump(docs):
    return HEADER + yaml.dump_all(docs, Dumper=Dumper, sort_keys=False, width=1000, allow_unicode=True)


def render():
    compose = yaml.safe_load((ROOT / "docker-compose.yml").read_text(encoding="utf-8"))
    topology = yaml.safe_load((ROOT / "deploy" / "mesh" / "topology.yaml").read_text(encoding="utf-8"))
    for name, service in EXTRA_SERVICES.items():
        if name in compose["services"]:
            fail(f"{name} đã có trong docker-compose.yml, bỏ khỏi EXTRA_SERVICES")
        compose["services"][name] = service
    build = Build(compose, topology)

    for service in list(WORKLOADS) + list(JOBS):
        if service not in build.services:
            fail(f"{service} không có trong docker-compose.yml")
    unplaced = [s for s in build.services if namespace_of(s) is None and s not in NOT_DEPLOYED]
    if unplaced:
        fail(f"service compose chưa được xếp vào lớp nào: {unplaced}")

    files = {}
    files["routes.yml"] = HEADER + yaml.safe_dump(build.routes(), sort_keys=False, width=1000, allow_unicode=True)
    files["namespaces.yaml"] = dump([
        {"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": ns}} for ns in ("ecommerce", "edge")
    ])
    files["aliases.yaml"] = dump(build.aliases())
    for service in WORKLOADS:
        files[f"{service}.yaml"] = dump(build.workload(service))
    for service in JOBS:
        files[f"{service}.yaml"] = dump(build.job(service))
    files["networkpolicies.yaml"] = dump(build.network_policies())
    # Không phải manifest: deploy/k8s/port-forward-dev.sh đọc file này (namespace, Service, host:cổng).
    files["port-forwards.txt"] = HEADER + "".join(f"{line}\n" for line in build.port_forwards())

    kustomization = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "labels": [{"pairs": {"app.kubernetes.io/part-of": "ecommerce"}, "includeSelectors": False}],
        "resources": [name for name in files if name.endswith(".yaml")],
        "configMapGenerator": build.configmaps,
    }
    files["kustomization.yaml"] = HEADER + yaml.safe_dump(kustomization, sort_keys=False, width=1000)
    return files


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    check = "--check" in sys.argv[1:]
    files = render()
    stale = []
    for name, content in files.items():
        path = OUT / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
    extra = sorted(p.name for p in OUT.glob("*") if p.is_file() and p.name not in files) if OUT.exists() else []
    if check:
        if stale or extra:
            sys.exit(f"deploy/k8s/services đã cũ: {stale + extra}; chạy python deploy/k8s/generate.py")
        print("deploy/k8s/services khớp docker-compose.yml")
        return
    for name in extra:
        (OUT / name).unlink()
    print(f"đã ghi {len(stale)} file, xoá {len(extra)} file trong deploy/k8s/services")


if __name__ == "__main__":
    main()
