#!/usr/bin/env python3
"""Generates the Istio ambient manifests from the mesh runtime contract (docs/mesh/decisions/ADR-001).

Inputs
  docs/mesh/runtime-contract.md   sections 5.1-5.3 (who may call what) and 8 (egress): the source of truth
  contracts/catalog/services.yaml service ids -> ServiceAccounts
  deploy/mesh/topology.yaml       ports, selectors and numbers the contract does not tabulate
  deploy/mesh/traffic-policy.yaml routes of section 7 as match expressions (numbers are cross-checked by the tests)
  deploy/mesh/versions.yaml       pinned versions

Output: deploy/mesh/generated/*.yaml and generated/coverage-report.md. Never edit them by hand.

    python deploy/mesh/generate.py            # write
    python deploy/mesh/generate.py --check    # exit 1 when the files on disk differ (CI)

Istio AuthorizationPolicy paths support only exact, prefix (`/x/*`) and suffix (`*/x`) matches, so a contract path with a
wildcard in the middle (`/internal/v1/carts/*/checkout-snapshot`) becomes the suffix `*/checkout-snapshot`, which is broader
than the contract. Every such rule is listed in coverage-report.md; the application allowlist (contracts ADR-004) is the exact
check behind it.
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

MESH_DIR = Path(__file__).resolve().parent
REPO = MESH_DIR.parents[1]
CONTRACT = REPO / "docs" / "mesh" / "runtime-contract.md"
SERVICES = REPO / "contracts" / "catalog" / "services.yaml"
OUT = MESH_DIR / "generated"

HEADER = (
    "# GENERATED by deploy/mesh/generate.py from docs/mesh/runtime-contract.md (mesh ADR-001). Do not edit by hand:\n"
    "# change the contract or the data files next to the generator and run `python deploy/mesh/generate.py`.\n"
)

DOMAIN = "cluster.local"
ISTIO_SECURITY = "security.istio.io/v1"
ISTIO_NETWORKING = "networking.istio.io/v1"


# --------------------------------------------------------------------------- reading the contract


def load_yaml(path: Path):
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def section(text: str, start: str, end: str) -> str:
    """Text between the heading line that starts with ``start`` and the next one that starts with ``end``."""
    lines = text.split("\n")
    first = next(i for i, line in enumerate(lines) if line.startswith(start))
    last = next(i for i in range(first + 1, len(lines)) if lines[i].startswith(end))
    return "\n".join(lines[first + 1:last])


def split_row(line: str) -> list[str]:
    """Split a Markdown table row on `|`, ignoring pipes inside backticks."""
    cells, current, in_code = [], [], False
    for char in line.strip().strip("|"):
        if char == "`":
            in_code = not in_code
        if char == "|" and not in_code:
            cells.append("".join(current).strip())
            current = []
        else:
            current.append(char)
    cells.append("".join(current).strip())
    return cells


def table_rows(text: str) -> list[list[str]]:
    rows = [split_row(line) for line in text.split("\n") if line.startswith("|")]
    return [row for row in rows[2:]]  # drop header and separator


def ticks(cell: str) -> list[str]:
    return re.findall(r"`([^`]+)`", cell)


def principal(token: str) -> str:
    namespace, name = token.split("/", 1)
    return f"{DOMAIN}/ns/{namespace}/sa/{name}"


def expand_alternatives(path: str) -> list[str]:
    """`/x/{a,b,c}` -> three paths. Braces without a comma are path parameters and stay."""
    match = re.search(r"\{([^{}]*,[^{}]*)\}", path)
    if not match:
        return [path]
    return [alt for option in match.group(1).split(",") for alt in expand_alternatives(path[:match.start()] + option.strip() + path[match.end():])]


def methods_of(cell: str) -> list[str] | None:
    cell = cell.strip()
    if cell == "X":
        return None
    return re.findall(r"[A-Z]{3,7}", re.sub(r"\(.*?\)", "", cell))


# --------------------------------------------------------------------------- path patterns


@dataclass(frozen=True)
class Pattern:
    value: str          # what goes into AuthorizationPolicy paths
    contract: str       # the path as the contract writes it
    broadened: bool     # true when the pattern allows more than the contract path

    def matches(self, path: str) -> bool:
        if self.value.endswith("*") and not self.value.startswith("*"):
            return path.startswith(self.value[:-1])
        if self.value.startswith("*"):
            return path.endswith(self.value[1:])
        return path == self.value


def to_patterns(path: str) -> list[Pattern]:
    """Istio patterns for one contract path.

    `/x/**` means the subtree *including* `/x` itself (`/api/v1/products/**` covers the collection `/api/v1/products`), but the
    Istio prefix `/x/*` does not match `/x`, so the base path is added as an exact pattern. `x**` glued to a name is a plain prefix.
    """
    contract = path
    path = re.sub(r"\{[^{}]+\}", "*", path)
    if "*" not in path:
        return [Pattern(path, contract, False)]
    if path.endswith("/**"):
        base = path[:-3]
        return [Pattern(base, contract, False), Pattern(base + "/*", contract, False)]
    if path.endswith("**"):
        return [Pattern(path[:-2] + "*", contract, False)]
    segments = path.split("/")
    last = max(i for i, segment in enumerate(segments) if "*" in segment)
    tail = segments[last + 1:]
    if not tail:
        return [Pattern("/".join(segments[:last]) + "/*", contract, True)]
    return [Pattern("*/" + "/".join(tail), contract, True)]


def samples(path: str) -> list[str]:
    """Concrete request paths that the contract path covers: wildcards become one segment, `/**` also yields the base path."""
    path = re.sub(r"\{[^{}]+\}", "x", path)
    if path.endswith("/**"):
        return [path[:-3], path[:-3] + "/x/y"]
    if path.endswith("**"):
        return [path[:-2], path[:-2] + "/x"]
    return [path.replace("*", "x")]


# --------------------------------------------------------------------------- the model


@dataclass
class Rule:
    destination: str
    port_name: str | None
    principals: list[str]
    patterns: list[Pattern]
    methods: list[str] | None
    source: str

    def allows(self, principal_name: str, method: str, path: str, port_name: str | None = None) -> bool:
        if principal_name not in self.principals:
            return False
        if self.methods is not None and method not in self.methods:
            return False
        if not any(pattern.matches(path) for pattern in self.patterns):
            return False
        return self.not_paths is None or not any(Pattern(v, v, False).matches(path) for v in self.not_paths)

    not_paths: list[str] | None = None


def parse_ecommerce_rules(contract_text: str) -> list[Rule]:
    rows = table_rows(section(contract_text, "### 5.2", "### 5.3"))
    rules = []
    for cells in rows:
        destination_cell, path_cell, method_cell, from_cell, source_cell = (cells + [""] * 5)[:5]
        destination_tokens = ticks(destination_cell)
        if not destination_tokens:
            continue  # "Mọi service" metrics row: handled as the namespace L4 baseline
        destination = destination_tokens[0]
        port_name = destination_tokens[1] if len(destination_tokens) > 1 else None
        principals = [principal(token) for token in ticks(from_cell) if "/" in token]
        paths = [expanded for token in ticks(path_cell) for expanded in expand_alternatives(token)]
        patterns = [pattern for path in paths for pattern in to_patterns(path)]
        rule = Rule(destination, port_name, principals, patterns, methods_of(method_cell), source_cell)
        # The Payment rows for Order must not cover the public Stripe webhook (contract section 5.2).
        if destination == "payment-service" and any(p.value.startswith("/v1/payments/") and p.value.endswith("*") for p in patterns):
            rule.not_paths = ["/v1/payments/webhook/*"]
        rules.append(rule)
    return rules


# --------------------------------------------------------------------------- manifests


def meta(name: str, namespace: str | None = None, labels: dict | None = None) -> dict:
    out: dict = {"name": name}
    if namespace:
        out["namespace"] = namespace
    base = {"app.kubernetes.io/part-of": "ecommerce-mesh", "app.kubernetes.io/managed-by": "deploy-mesh-generate"}
    out["labels"] = {**base, **(labels or {})}
    return out


def namespaces(topology: dict) -> list[dict]:
    docs = []
    for name, spec in topology["namespaces"].items():
        labels = {}
        if spec["dataplane"]:
            labels["istio.io/dataplane-mode"] = spec["dataplane"]
        if spec["waypoint"]:
            labels["istio.io/use-waypoint"] = spec["waypoint"]
        docs.append({"apiVersion": "v1", "kind": "Namespace", "metadata": meta(name, labels=labels)})
    return docs


def service_accounts(topology: dict) -> list[dict]:
    ids = [s["id"] for s in load_yaml(SERVICES)["services"] if s["id"] != "api-gateway"]
    plan = {"ecommerce": ids,
            "edge": list(topology["edge_workloads"]),
            "observability": list(topology["observability_workloads"])}
    docs = []
    for namespace, names in plan.items():
        for name in sorted(set(names)):
            docs.append({"apiVersion": "v1", "kind": "ServiceAccount", "metadata": meta(name, namespace),
                         "automountServiceAccountToken": False})
    return docs


def peer_authentication() -> list[dict]:
    return [
        {"apiVersion": ISTIO_SECURITY, "kind": "PeerAuthentication", "metadata": meta("default", "istio-system"),
         "spec": {"mtls": {"mode": "STRICT"}}},
        {"apiVersion": ISTIO_SECURITY, "kind": "PeerAuthentication", "metadata": meta("traefik-public-ports", "edge"),
         "spec": {"selector": {"matchLabels": {"app.kubernetes.io/name": "traefik"}},
                  "mtls": {"mode": "STRICT"},
                  "portLevelMtls": {"80": {"mode": "PERMISSIVE"}, "443": {"mode": "PERMISSIVE"}}}},
    ]


def waypoint(topology: dict) -> list[dict]:
    spec = topology["waypoint"]
    name, namespace = spec["name"], spec["namespace"]
    return [
        {"apiVersion": "gateway.networking.k8s.io/v1", "kind": "Gateway",
         "metadata": meta(name, namespace, {"istio.io/waypoint-for": "service"}),
         "spec": {"gatewayClassName": "istio-waypoint", "listeners": [{"name": "mesh", "port": 15008, "protocol": "HBONE"}]}},
        {"apiVersion": "policy/v1", "kind": "PodDisruptionBudget", "metadata": meta(name, namespace),
         "spec": {"minAvailable": 1,
                  "selector": {"matchLabels": {"gateway.networking.k8s.io/gateway-name": name}}}},
        {"apiVersion": "autoscaling/v2", "kind": "HorizontalPodAutoscaler", "metadata": meta(name, namespace),
         "spec": {"scaleTargetRef": {"apiVersion": "apps/v1", "kind": "Deployment", "name": name},
                  "minReplicas": spec["min_replicas"], "maxReplicas": spec["max_replicas"],
                  "metrics": [{"type": "Resource", "resource": {"name": "cpu",
                               "target": {"type": "Utilization", "averageUtilization": spec["cpu_target_percent"]}}}]}},
    ]


def authz(name: str, namespace: str, spec: dict) -> dict:
    return {"apiVersion": ISTIO_SECURITY, "kind": "AuthorizationPolicy", "metadata": meta(name, namespace), "spec": spec}


def ecommerce_policies(topology: dict, rules: list[Rule]) -> list[dict]:
    waypoint_name = topology["waypoint"]["name"]
    waypoint_principal = principal(f"ecommerce/{waypoint_name}")
    prometheus = principal("observability/prometheus")
    docs = [
        # ztunnel (L4): after the waypoint took over, only the waypoint and the metrics scraper may reach a pod.
        authz("l4-baseline", "ecommerce", {"action": "ALLOW", "rules": [{"from": [{"source": {"principals": [waypoint_principal, prometheus]}}]}]}),
        # waypoint (L7): nothing is allowed unless a per-Service policy below says so.
        authz("deny-all", "ecommerce", {"action": "ALLOW", "targetRefs": [{"group": "gateway.networking.k8s.io", "kind": "Gateway", "name": waypoint_name}]}),
    ]
    by_destination: dict[str, list[Rule]] = {}
    for rule in rules:
        by_destination.setdefault(rule.destination, []).append(rule)
    for destination in sorted(by_destination):
        policy_rules = []
        for rule in by_destination[destination]:
            operation: dict = {"paths": sorted({p.value for p in rule.patterns})}
            if rule.methods:
                operation["methods"] = rule.methods
            if rule.not_paths:
                operation["notPaths"] = rule.not_paths
            policy_rules.append({"from": [{"source": {"principals": rule.principals}}], "to": [{"operation": operation}]})
        docs.append(authz(f"allow-{destination}", "ecommerce", {
            "action": "ALLOW",
            "targetRefs": [{"group": "", "kind": "Service", "name": destination}],
            "rules": policy_rules}))
    return docs


def parse_port_cell(cell: str, ports: dict) -> list[int]:
    numbers = [int(n) for n in re.findall(r"\b(\d{2,5})\b", cell)]
    if numbers:
        return numbers
    word = cell.strip().lower()
    for key in ("metrics", "http", "web"):
        if key in word and key in ports:
            return [ports[key]]
    return [ports.get("http", next(iter(ports.values())))]


def l4_policies(topology: dict, contract_text: str) -> list[dict]:
    docs = [authz("deny-all", "edge", {"action": "ALLOW"}), authz("deny-all", "observability", {"action": "ALLOW"})]
    # --- 5.1 edge
    edge = topology["edge_workloads"]
    grouped: dict[str, list[dict]] = {}
    for cells in table_rows(section(contract_text, "### 5.1", "### 5.2")):
        destination = re.sub(r"[`\s]", "", cells[0]).lower()
        workload = "traefik" if destination == "traefik" else destination
        if workload not in edge:
            continue
        ports = parse_port_cell(cells[1], edge[workload]["ports"])
        sources = [principal(t) for t in ticks(cells[2]) if "/" in t]
        rule: dict = {"to": [{"operation": {"ports": [str(p) for p in ports]}}]}
        if sources:
            rule["from"] = [{"source": {"principals": sources}}]
        grouped.setdefault(workload, []).append(rule)
    for workload in sorted(grouped):
        docs.append(authz(f"allow-{workload}", "edge", {
            "action": "ALLOW", "selector": {"matchLabels": edge[workload]["selector"]}, "rules": grouped[workload]}))
    # --- 5.3 observability
    workloads = topology["observability_workloads"]
    for cells in table_rows(section(contract_text, "### 5.3", "## 6.")):
        name = re.sub(r"[`\s]", "", cells[0]).lower()
        if name.startswith("otelcollector"):
            names = ["otel-collector"]
        elif name.startswith("prometheus"):
            names = ["prometheus", "jaeger", "loki"]
        else:
            continue  # Grafana: access policy outside the mesh
        namespaces_allowed = [t.split("/")[0] for t in ticks(cells[2]) if t.endswith("/*")]
        principals_allowed = [principal(t) for t in ticks(cells[2]) if "/" in t and not t.endswith("/*")]
        for workload in names:
            source: dict = {}
            if namespaces_allowed:
                source["namespaces"] = namespaces_allowed
            if principals_allowed:
                source["principals"] = principals_allowed
            if not source:
                continue
            docs.append(authz(f"allow-{workload}", "observability", {
                "action": "ALLOW", "selector": {"matchLabels": workloads[workload]["selector"]},
                "rules": [{"from": [{"source": source}],
                           "to": [{"operation": {"ports": [str(p) for p in workloads[workload]["ports"].values()]}}]}]}))
    return docs


def host(service: str) -> str:
    return f"{service}.ecommerce.svc.{DOMAIN}"


def route_match(route: dict, port: int | None) -> dict:
    match: dict = {}
    if route.get("methods") and len(route["methods"]) == 1:
        match["method"] = {"exact": route["methods"][0]}
    elif route.get("methods"):
        match["method"] = {"regex": "|".join(route["methods"])}
    if "exact" in route:
        match["uri"] = {"exact": route["exact"]}
    elif "prefix" in route:
        match["uri"] = {"prefix": route["prefix"]}
    else:
        match["uri"] = {"regex": route["regex"]}
    if port is not None:
        match["port"] = port
    return match


def virtual_services(topology: dict, policy: dict) -> list[dict]:
    by_service: dict[str, list[dict]] = {}
    for route in policy["routes"]:
        by_service.setdefault(route["service"], []).append(route)
    docs = []
    for service in sorted(by_service):
        ports = topology["services"][service]["ports"]
        multi_port = len(ports) > 1
        http = []
        for route in by_service[service]:
            port = ports[route.get("port", "http")]
            attempts = route["attempts"]
            timeout = route["timeout_s"]
            retries: dict = {"attempts": attempts}
            if attempts > 0:
                retries["perTryTimeout"] = f"{max(1, timeout // (attempts + 1))}s"
                retries["retryOn"] = route["retry_on"]
            entry: dict = {"name": route["id"], "match": [route_match(route, port if multi_port else None)],
                           "route": [{"destination": {"host": host(service), "port": {"number": port}}}],
                           "timeout": f"{timeout}s", "retries": retries}
            http.append(entry)
        # A route that matches nothing above (public traffic through Traefik) is not rewritten: mesh defaults apply
        # (meshConfig.defaultHttpRetryPolicy.attempts: 0), and no timeout is set at the mesh (contract section 7).
        http.append({"name": "default", "route": [{"destination": {"host": host(service)}}]})
        docs.append({"apiVersion": ISTIO_NETWORKING, "kind": "VirtualService", "metadata": meta(service, "ecommerce"),
                     "spec": {"hosts": [host(service)], "http": http}})
    return docs


def destination_rules(topology: dict) -> list[dict]:
    settings = topology["destination_rule"]
    outlier = settings["outlier_detection"]
    docs = []
    for service in sorted(topology["services"]):
        docs.append({"apiVersion": ISTIO_NETWORKING, "kind": "DestinationRule", "metadata": meta(service, "ecommerce"),
                     "spec": {"host": host(service), "trafficPolicy": {
                         "loadBalancer": {"simple": settings["load_balancer"]},
                         "connectionPool": {"tcp": {"maxConnections": settings["connection_pool"]["tcp"]["max_connections"]},
                                            "http": {"http1MaxPendingRequests": settings["connection_pool"]["http"]["http1_max_pending_requests"],
                                                     "http2MaxRequests": settings["connection_pool"]["http"]["http2_max_requests"]}},
                         "outlierDetection": {"consecutive5xxErrors": outlier["consecutive5xx_errors"],
                                              "interval": outlier["interval"], "baseEjectionTime": outlier["base_ejection_time"],
                                              "maxEjectionPercent": outlier["max_ejection_percent"]}}}})
    return docs


def service_entries(topology: dict) -> list[dict]:
    return [{"apiVersion": ISTIO_NETWORKING, "kind": "ServiceEntry",
             "metadata": {**meta(entry["name"], "ecommerce"), "annotations": {"mesh.ecommerce/owner": entry["owner"]}},
             "spec": {"hosts": [entry["host"]], "location": "MESH_EXTERNAL", "resolution": "DNS", "exportTo": ["."],
                      "ports": [{"number": entry["port"], "name": "tls", "protocol": "TLS"}]}}
            for entry in topology["egress"]]


def telemetry(versions: dict) -> list[dict]:
    return [{"apiVersion": "telemetry.istio.io/v1", "kind": "Telemetry", "metadata": meta("default", "istio-system"),
             "spec": {"tracing": [{"providers": [{"name": "otel"}],
                                   "randomSamplingPercentage": versions["observability"]["tracing_sampling_percent"]}],
                      "accessLogging": [{"providers": [{"name": "envoy"}]}]}}]


def network_policies() -> list[dict]:
    def selector(*names: str) -> dict:
        return {"namespaceSelector": {"matchExpressions": [{"key": "kubernetes.io/metadata.name", "operator": "In", "values": list(names)}]}}
    return [
        {"apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy", "metadata": meta("default-deny-ingress", "ecommerce"),
         "spec": {"podSelector": {}, "policyTypes": ["Ingress"]}},
        # Independent of the mesh (contract section 10): only the mesh namespaces and the namespace itself may open connections.
        {"apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy", "metadata": meta("allow-mesh-and-edge", "ecommerce"),
         "spec": {"podSelector": {}, "policyTypes": ["Ingress"],
                  "ingress": [{"from": [selector("edge", "ecommerce", "observability", "istio-system")]}]}},
    ]


# --------------------------------------------------------------------------- output


def dump(documents: list[dict]) -> str:
    return HEADER + "---\n" + "---\n".join(yaml.safe_dump(d, sort_keys=False, default_flow_style=False, width=120, allow_unicode=True) for d in documents)


def coverage_report(rules: list[Rule]) -> str:
    lines = [
        "# AuthorizationPolicy coverage report",
        "",
        "Generated with the manifests; do not edit. Each row of runtime-contract section 5.2 becomes one rule. A rule marked",
        "**broader** allows more paths than the contract states, because Istio matches only exact, prefix and suffix patterns.",
        "The principal restriction is exact in every case; the application allowlist ([contracts ADR-004](../../../contracts/decisions/ADR-004-service-identity-allowlist.md))",
        "is the exact check behind it.",
        "",
        "| Destination | Principals | Methods | Contract path | Istio pattern | Match |",
        "|---|---|---|---|---|---|",
    ]
    for rule in rules:
        for pattern in rule.patterns:
            who = ", ".join(p.split("/ns/")[1].replace("/sa/", "/") for p in rule.principals)
            lines.append(f"| {rule.destination}{' (' + rule.port_name + ')' if rule.port_name else ''} | {who} | "
                         f"{', '.join(rule.methods) if rule.methods else 'any'} | `{pattern.contract}` | `{pattern.value}` | "
                         f"{'**broader**' if pattern.broadened else 'exact'} |")
    broader = sum(p.broadened for r in rules for p in r.patterns)
    total = sum(len(r.patterns) for r in rules)
    lines += ["", f"{total} patterns, {broader} broader than the contract path."]
    return "\n".join(lines) + "\n"


def build() -> dict[str, str]:
    contract_text = CONTRACT.read_text(encoding="utf-8")
    topology = load_yaml(MESH_DIR / "topology.yaml")
    policy = load_yaml(MESH_DIR / "traffic-policy.yaml")
    versions = load_yaml(MESH_DIR / "versions.yaml")
    rules = parse_ecommerce_rules(contract_text)
    return {
        "00-namespaces.yaml": dump(namespaces(topology)),
        "10-serviceaccounts.yaml": dump(service_accounts(topology)),
        "20-peerauthentication.yaml": dump(peer_authentication()),
        "30-waypoint.yaml": dump(waypoint(topology)),
        "40-authorizationpolicies-l4.yaml": dump(l4_policies(topology, contract_text)),
        "41-authorizationpolicies-ecommerce.yaml": dump(ecommerce_policies(topology, rules)),
        "50-virtualservices.yaml": dump(virtual_services(topology, policy)),
        "51-destinationrules.yaml": dump(destination_rules(topology)),
        "60-serviceentries.yaml": dump(service_entries(topology)),
        "70-telemetry.yaml": dump(telemetry(versions)),
        "80-networkpolicies.yaml": dump(network_policies()),
        "coverage-report.md": coverage_report(rules),
    }


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the generated files on disk are out of date")
    args = parser.parse_args(argv)
    files = build()
    if args.check:
        stale = [name for name, content in files.items()
                 if not (OUT / name).exists() or (OUT / name).read_text(encoding="utf-8").replace("\r\n", "\n") != content]
        extra = [p.name for p in OUT.glob("*") if p.name not in files] if OUT.exists() else []
        if stale or extra:
            print("generated manifests are out of date: " + ", ".join(stale + extra), file=sys.stderr)
            print("run: python deploy/mesh/generate.py", file=sys.stderr)
            return 1
        print(f"{len(files)} generated files are up to date")
        return 0
    OUT.mkdir(exist_ok=True)
    for name, content in files.items():
        (OUT / name).write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {len(files)} files to {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
